// node src/buddy/sync-detectors.mjs: copies the server's deterministic detectors (src/app/api/vscode/check/detectors.ts,
// owned by agent H) into src/buddy/vendor/ so the buddy flags exactly what POST /api/vscode/check will, before it answers.
// Re-run after the server detectors change; src/buddy/local.selftest.mjs checks local == server.
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const api = join(here, "..", "..", "..", "src", "app", "api", "vscode");
const out = join(here, "vendor");
mkdirSync(out, { recursive: true });
const banner = (src) => `// GENERATED by src/buddy/sync-detectors.mjs from ${src}. Do not edit; re-run the script.\n/* eslint-disable */\n`;

const detectors = readFileSync(join(api, "check", "detectors.ts"), "utf8")
  .replace(`from "../shared"`, `from "./shared"`)
  .replace(`from "../types"`, `from "../../types"`);
writeFileSync(join(out, "detectors.ts"), banner("src/app/api/vscode/check/detectors.ts") + detectors);

// Only the pure parts of shared.ts: wording + the signature parser (no DB, no server-only imports).
const shared = readFileSync(join(api, "shared.ts"), "utf8");
const section = (from, to) => {
  const a = shared.indexOf(from);
  const b = to ? shared.indexOf(to, a) : shared.length;
  if (a < 0 || b < 0) throw new Error(`shared.ts changed: can't find "${from}"`);
  return shared.slice(a, b);
};
writeFileSync(
  join(out, "shared.ts"),
  banner("src/app/api/vscode/shared.ts (wording + signature parser)") +
    `import type { Violation, VsRule } from "../../types";\n\n` +
    section("// ---------- wording", "// ---------- rule loading") +
    section("// ---------- function signatures"),
);
console.log("synced detectors.ts + shared.ts into", out);
